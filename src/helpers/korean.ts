export function phoneToKorean(val: string | null): string | null {
  let result = '';

  if (!val || val.length < 4) {
    return null;
  }
  // '-' 문자 제거
  const cleanPhone = val.replace(/-/g, '').slice(3);

  // 2개 문자씩 읽어서 처리
  for (let i = 0; i < cleanPhone.length; i += 2) {
    const pair = cleanPhone.slice(i, i + 2);
    const index = parseInt(pair, 10);
    result += koreanSyllables100[index];
  }

  return result;
}

export function koreanToPhone(val: string): string {
  let result = '';

  for (const char of val) {
    const index = koreanSyllables100.indexOf(char);
    if (index === -1) {
      throw new Error(
        `Character '${char}' not found in the Korean syllables array.`,
      );
    }
    const digits = index.toString().padStart(2, '0');
    result += digits;
  }

  return `010${result}`;
}
